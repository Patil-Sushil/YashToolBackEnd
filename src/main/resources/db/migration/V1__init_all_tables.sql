-- ============================================================
-- ENQUIRIES (UPDATED)
-- ============================================================

CREATE TABLE IF NOT EXISTS enquiries (
                                         id UUID PRIMARY KEY DEFAULT gen_random_uuid(),

    -- Audit fields
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP,
    created_by VARCHAR(255),
    updated_by VARCHAR(255),

    -- Business fields
    enquiry_no VARCHAR(20) NOT NULL UNIQUE,
    customer_id UUID NOT NULL,
    is_urgent BOOLEAN NOT NULL DEFAULT FALSE,
    status VARCHAR(20) NOT NULL DEFAULT 'CREATED',

    -- Foreign key
    CONSTRAINT fk_enquiry_customer
    FOREIGN KEY (customer_id)
    REFERENCES customers(id)
    ON DELETE RESTRICT,

    -- Status constraint
    CONSTRAINT chk_enquiry_status CHECK (
                                            status IN ('CREATED', 'UNDER_REVIEW', 'QUOTED', 'ACCEPTED', 'CLOSED')
    )
    );

-- ============================================================
-- ENQUIRY ITEMS (UPDATED - REMOVED sample_provided, remarks moved here only)
-- ============================================================

CREATE TABLE IF NOT EXISTS enquiry_items (
                                             id UUID PRIMARY KEY DEFAULT gen_random_uuid(),

    -- Foreign key
    enquiry_id UUID NOT NULL,

    -- Business fields
    order_type VARCHAR(20) NOT NULL,
    tool_name VARCHAR(200) NOT NULL,
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    trial BOOLEAN NOT NULL DEFAULT FALSE,

    -- Optional fields
    remarks TEXT,
    drawing_reference VARCHAR(500),

    -- Foreign key constraint
    CONSTRAINT fk_item_enquiry
    FOREIGN KEY (enquiry_id)
    REFERENCES enquiries(id)
    ON DELETE CASCADE,

    -- Order type constraint
    CONSTRAINT chk_order_type CHECK (
                                        order_type IN ('NEW_TOOL', 'RESHARPENING', 'REFORMING')
    )
    );

-- ============================================================
-- NEW TOOL SPECS (UPDATED - Added Material Type/Grade, Boolean Coating)
-- ============================================================

CREATE TABLE IF NOT EXISTS new_tool_specs (
                                              id UUID PRIMARY KEY DEFAULT gen_random_uuid(),

    -- Foreign key
    enquiry_item_id UUID NOT NULL UNIQUE,

    -- Material specifications (NEW)
    material_type VARCHAR(30) NOT NULL,
    material_grade VARCHAR(30) NOT NULL,

    -- Coating specifications (UPDATED)
    coating_required BOOLEAN NOT NULL DEFAULT FALSE,
    coating_type VARCHAR(30),

    -- Dimensional specifications (FIXED: DOUBLE PRECISION to match Java Double)
    diameter DOUBLE PRECISION NOT NULL CHECK (diameter > 0),
    flute_length DOUBLE PRECISION NOT NULL CHECK (flute_length > 0),
    shank_diameter DOUBLE PRECISION NOT NULL CHECK (shank_diameter > 0),
    overall_length DOUBLE PRECISION NOT NULL CHECK (overall_length > 0),

    -- Technical notes
    technical_notes TEXT,

    -- Foreign key constraint
    CONSTRAINT fk_new_tool_item
    FOREIGN KEY (enquiry_item_id)
    REFERENCES enquiry_items(id)
    ON DELETE CASCADE,

    -- Material type constraint
    CONSTRAINT chk_material_type CHECK (
                                           material_type IN ('HSS', 'CARBIDE', 'COBALT_HSS', 'PM_HSS', 'TOOL_STEEL')
    ),

    -- Material grade constraint
    CONSTRAINT chk_material_grade CHECK (
                                            material_grade IN ('M2', 'M35', 'M42', 'K10', 'K20', 'K30', 'O1', 'A2', 'D2', 'ASP23', 'ASP30')
    ),

    -- Coating type constraint
    CONSTRAINT chk_new_tool_coating_type CHECK (
                                                   coating_type IS NULL OR coating_type IN ('HELICA', 'ALCRONA', 'VICIOUS_BLACK', 'VICIOUS_BROWN')
    )
    );

