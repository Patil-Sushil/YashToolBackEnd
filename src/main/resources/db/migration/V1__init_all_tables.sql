-- View: Active enquiries with customer details
CREATE OR REPLACE VIEW v_active_enquiries AS
SELECT
    e.id AS enquiry_id,
    e.enquiry_no,
    e.created_at,
    e.is_urgent,
    e.status,
    c.id AS customer_id,
    c.company_name,
    c.customer_name,
    c.email,
    c.mobile_number,
    COUNT(ei.id) AS item_count,
    BOOL_OR(ei.trial) AS has_trial
FROM enquiries e
         INNER JOIN customers c ON e.customer_id = c.id
         LEFT JOIN enquiry_items ei ON e.id = ei.enquiry_id
WHERE e.status != 'CLOSED'
  AND c.is_deleted = FALSE
GROUP BY e.id, c.id;

-- View: Enquiry items with specifications summary
CREATE OR REPLACE VIEW v_enquiry_items_summary AS
SELECT
    ei.id AS item_id,
    ei.enquiry_id,
    ei.order_type,
    ei.tool_name,
    ei.quantity,
    ei.trial,
    CASE
        WHEN nts.id IS NOT NULL THEN 'NEW_TOOL'
        WHEN rs.id IS NOT NULL THEN 'RESHARPENING'
        WHEN rfs.id IS NOT NULL THEN 'REFORMING'
        ELSE 'UNKNOWN'
        END AS spec_type,
    CASE
        WHEN nts.coating_required = TRUE THEN nts.coating_type
        WHEN rs.coating_required = TRUE THEN rs.coating_type
        WHEN rfs.coating_required = TRUE THEN rfs.coating_type
        ELSE NULL
        END AS coating_type,
    nts.material_type,
    nts.material_grade
FROM enquiry_items ei
         LEFT JOIN new_tool_specs nts ON ei.id = nts.enquiry_item_id
         LEFT JOIN resharpening_specs rs ON ei.id = rs.enquiry_item_id
         LEFT JOIN reforming_specs rfs ON ei.id = rfs.enquiry_item_id;

