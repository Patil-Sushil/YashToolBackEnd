-- Function: Generate next enquiry number
CREATE OR REPLACE FUNCTION generate_enquiry_number()
    RETURNS VARCHAR(20) AS $$
DECLARE
current_year INTEGER;
    next_sequence INTEGER;
    last_enquiry_no VARCHAR(20);
    last_year INTEGER;
BEGIN
    current_year := EXTRACT(YEAR FROM CURRENT_DATE);

    -- Get last enquiry number
SELECT enquiry_no INTO last_enquiry_no
FROM enquiries
ORDER BY created_at DESC
    LIMIT 1;

IF last_enquiry_no IS NULL THEN
        next_sequence := 1;
ELSE
        -- Extract year and sequence from last enquiry number
        last_year := CAST(SPLIT_PART(last_enquiry_no, '-', 2) AS INTEGER);

        IF last_year = current_year THEN
            next_sequence := CAST(SPLIT_PART(last_enquiry_no, '-', 3) AS INTEGER) + 1;
ELSE
            next_sequence := 1;
END IF;
END IF;

RETURN 'ENQ-' || current_year || '-' || LPAD(next_sequence::TEXT, 4, '0');
END;
$$ LANGUAGE plpgsql;

-- Function: Check trial quantity validation
CREATE OR REPLACE FUNCTION validate_trial_quantity()
    RETURNS TRIGGER AS $$
BEGIN
    IF NEW.trial = TRUE AND NEW.quantity > 1 THEN
        RAISE EXCEPTION 'Trial quantity cannot exceed 1. Current quantity: %', NEW.quantity;
END IF;
RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- Trigger: Validate trial items before insert/update
CREATE TRIGGER trg_validate_trial_quantity
    BEFORE INSERT OR UPDATE ON enquiry_items
                         FOR EACH ROW
                         EXECUTE FUNCTION validate_trial_quantity();

-- Function: Update timestamp on update
CREATE OR REPLACE FUNCTION update_timestamp()
    RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- Triggers: Auto-update timestamps
CREATE TRIGGER trg_customers_updated_at
    BEFORE UPDATE ON customers
    FOR EACH ROW
    EXECUTE FUNCTION update_timestamp();

CREATE TRIGGER trg_enquiries_updated_at
    BEFORE UPDATE ON enquiries
    FOR EACH ROW
    EXECUTE FUNCTION update_timestamp();

